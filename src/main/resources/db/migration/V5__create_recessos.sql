-- Períodos em que a barbearia não atende (ex.: férias); o intervalo é inclusivo nas duas pontas.
CREATE TABLE IF NOT EXISTS recessos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(128) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL
);

-- Validação de agendamento (data dentro de um recesso) e de sobreposição entre recessos.
CREATE INDEX IF NOT EXISTS idx_recessos_data_inicio_data_fim ON recessos (data_inicio, data_fim);
