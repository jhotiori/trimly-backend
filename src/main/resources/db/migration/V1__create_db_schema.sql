-- Usuários do sistema; o cargo (CLIENTE, ADMIN, DONO) define as permissões.
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    -- UNIQUE cria o índice usado no login e em cada requisição autenticada (busca por e-mail).
    email VARCHAR(255) NOT NULL UNIQUE,
    -- Hash BCrypt, nunca a senha em texto puro.
    senha VARCHAR(255) NOT NULL,
    cargo VARCHAR(20) NOT NULL
);

-- Serviços oferecidos pela barbearia.
CREATE TABLE IF NOT EXISTS servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL UNIQUE,
    valor DECIMAL(10, 2) NOT NULL,
    -- Duração em minutos.
    duracao INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL
);

-- Janelas de atendimento por dia da semana; um dia pode ter várias janelas.
CREATE TABLE IF NOT EXISTS disponibilidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana VARCHAR(10) NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL
);

-- Agendamento de um serviço por um usuário.
CREATE TABLE IF NOT EXISTS agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Data e hora de início do atendimento.
    data TIMESTAMP NOT NULL,
    -- Duração em minutos, copiada do serviço no momento do agendamento.
    duracao INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    usuario_id BIGINT NOT NULL,
    servico_id BIGINT NOT NULL,
    CONSTRAINT fk_agendamentos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_agendamentos_servico FOREIGN KEY (servico_id) REFERENCES servicos (id)
);
